/**
 * Mendeteksi nama merek secara otomatis dari nama produk (atau brand grup varian).
 * Mengembalikan null bila produk termasuk barang curah/generik tanpa merek.
 */
export function detectBrandFromName(
  namaProduk: string,
  groupBrand?: string | null
): string | null {
  const explicitGroupBrand = groupBrand?.trim();
  if (explicitGroupBrand) return explicitGroupBrand;

  const clean = namaProduk.trim().replace(/\s+/g, " ");
  if (!clean) return null;

  for (const rule of BRAND_RULES) {
    if (rule.pattern.test(clean)) {
      return rule.brand;
    }
  }

  return null;
}

/**
 * Menentukan merek efektif dengan fallback deteksi otomatis bila merek kosong.
 */
export function resolveProductBrand(params: {
  merek?: string | null;
  nama: string;
  groupBrand?: string | null;
}): string | null {
  if (params.merek !== undefined) {
    const trimmed = params.merek?.trim();
    return trimmed || null;
  }
  return detectBrandFromName(params.nama, params.groupBrand);
}
